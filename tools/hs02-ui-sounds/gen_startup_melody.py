#!/usr/bin/env python3
"""Bake the power-on melody for the HS-02 buzzer.

Input:  tools/hs02-ui-sounds/startup.rtttl  (one RTTTL ringtone, "name:d=4,o=5,b=120:notes")
Output: source/Core/BSP/Fnirsi/Hs02StartupMelody.h   (a table of {frequency Hz, duration ms})
        tools/hs02-ui-sounds/startup_preview.wav      (what the buzzer will roughly sound like)

The buzzer is a single piezo driven by a square wave, so only one note sounds at a time. Notes
between ~1 and ~4 kHz (octaves 6-7) are the loudest; use TRANSPOSE to move a low tune up.

Usage:  python3 tools/hs02-ui-sounds/gen_startup_melody.py [--transpose N]   (N in semitones)
"""
import argparse
import math
import re
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(__file__).resolve().parent / "startup.rtttl"
OUT = ROOT / "source/Core/BSP/Fnirsi/Hs02StartupMelody.h"
WAV = Path(__file__).resolve().parent / "startup_preview.wav"

SEMITONE = {"c": 0, "c#": 1, "d": 2, "d#": 3, "e": 4, "f": 5, "f#": 6, "g": 7, "g#": 8, "a": 9, "a#": 10, "b": 11, "h": 11}
GAP_MS = 12  # silence after every note, so repeated notes stay separate (like phone ringtones)
NOTE_RE = re.compile(r"^(\d+)?([a-hp]#?)(\.?)(\d)?(\.?)$")


def parse(text: str, transpose: int):
    name, defaults, body = text.strip().split(":", 2)
    d, o, b = 4, 6, 63
    for item in defaults.split(","):
        key, _, value = item.strip().partition("=")
        if key.strip() == "d":
            d = int(value)
        elif key.strip() == "o":
            o = int(value)
        elif key.strip() == "b":
            b = int(value)
    whole_ms = 4 * 60000 / b
    notes = []
    for token in body.split(","):
        token = token.strip().lower()
        if not token:
            continue
        m = NOTE_RE.match(token)
        if not m:
            raise SystemExit(f"bad RTTTL note: {token!r}")
        dur = int(m.group(1)) if m.group(1) else d
        ms = whole_ms / dur
        if m.group(3) or m.group(5):
            ms *= 1.5
        if m.group(2) == "p":
            notes.append((0, round(ms)))
            continue
        octave = int(m.group(4)) if m.group(4) else o
        n = octave * 12 + SEMITONE[m.group(2)] + transpose
        freq = 440.0 * 2 ** ((n - 57) / 12)  # A4 = 57
        ms = round(ms)
        if ms > 2 * GAP_MS:
            notes.append((round(freq), ms - GAP_MS))
            notes.append((0, GAP_MS))
        else:
            notes.append((round(freq), ms))
    # merge neighbouring rests
    merged = []
    for freq, ms in notes:
        if merged and freq == 0 and merged[-1][0] == 0:
            merged[-1] = (0, merged[-1][1] + ms)
        else:
            merged.append((freq, ms))
    return name.strip(), merged


def preview(notes, path, duty=0.066, rate=22050):
    frames = bytearray()
    for freq, ms in notes:
        count = int(rate * ms / 1000)
        for i in range(count):
            if freq:
                phase = (i * freq / rate) % 1.0
                v = 9000 if phase < duty else -900
            else:
                v = 0
            frames += struct.pack("<h", v)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(bytes(frames))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--transpose", type=int, default=0, help="semitones, e.g. 12 = one octave up")
    ap.add_argument("--wav", default=str(WAV), help="where to write the preview")
    args = ap.parse_args()
    name, notes = parse(SRC.read_text(encoding="utf-8"), args.transpose)
    total = sum(ms for _, ms in notes)
    lines = [
        "#pragma once",
        "// GENERATED by tools/hs02-ui-sounds/gen_startup_melody.py -- do not edit by hand.",
        f"// Power-on melody \"{name}\": {len(notes)} notes, {total} ms (transpose {args.transpose:+d}).",
        "#include <stdint.h>",
        "",
        "struct Hs02MelodyNote {",
        "  uint16_t hz; // 0 = rest",
        "  uint16_t ms;",
        "};",
        "",
        "static const Hs02MelodyNote kHs02StartupMelody[] = {",
    ]
    for freq, ms in notes:
        lines.append(f"    {{{freq}, {ms}}},")
    lines += ["};", f"static const uint16_t kHs02StartupMelodyLength = {len(notes)};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    preview(notes, args.wav)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(notes)} entries, {total / 1000:.2f} s; preview {args.wav}")
    lo = min((f for f, _ in notes if f), default=0)
    if lo and lo < 900:
        print(f"note: the lowest note is {lo} Hz; the piezo is quiet below ~1 kHz (try --transpose 12)")


if __name__ == "__main__":
    sys.exit(main())
