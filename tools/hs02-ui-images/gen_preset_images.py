#!/usr/bin/env python3
"""Bake the pictures of the HS-02 picture screens.

Input:  tools/hs02-ui-images/presets/ (any size / format Pillow reads)
          preset1.png .. preset3.png - "ready" screen while the target equals Settings > Tip > Preset N
          standby.png                - standby screen after power-on (heater off, tip cold)
Output: source/Core/Threads/UI/drawing/color_160x80/Hs02PresetImages.hpp

Each picture is scaled to cover 160x64 (centre crop) and stored as 2 bits per pixel. The LCD
frame only has 4 colours per row band, so the picture is cut into bands of BAND_ROWS rows and
every band gets its own best 4 colours (k-means, no dithering: crisp pixel-art edges).
Cost: 2560 bytes of pixels + 16 x 8 bytes of palettes per picture.

Requires Pillow and numpy. Usage:  python3 tools/hs02-ui-images/gen_preset_images.py
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC_DIR = Path(__file__).resolve().parent / "presets"
OUT = ROOT / "source/Core/Threads/UI/drawing/color_160x80/Hs02PresetImages.hpp"

WIDTH, HEIGHT = 160, 64
BAND_ROWS = 4
NAMES = ["preset1", "preset2", "preset3", "standby"]  # index in kPictures = position here


def rgb565(c):
    r, g, b = c
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def load(path: Path) -> Image.Image:
    im = Image.open(path).convert("RGB")
    scale = max(WIDTH / im.width, HEIGHT / im.height)
    im = im.resize((max(WIDTH, round(im.width * scale)), max(HEIGHT, round(im.height * scale))), Image.LANCZOS)
    left, top = (im.width - WIDTH) // 2, (im.height - HEIGHT) // 2
    return im.crop((left, top, left + WIDTH, top + HEIGHT))


def band_palette(pixels, k=4, iterations=12):
    """k-means with farthest-point seeding: keeps small bright details (a thin line, a star)
    instead of spending every colour on a large gradient, which median cut tends to do."""
    pts = np.asarray(pixels, dtype=np.float32)
    uniq = np.unique(pts, axis=0)
    if len(uniq) <= k:
        centres = list(uniq) + [uniq[0]] * (k - len(uniq))
        return np.asarray(centres, dtype=np.float32)
    centres = [pts.mean(axis=0)]
    centres[0] = uniq[np.argmin(((uniq - centres[0]) ** 2).sum(axis=1))]
    while len(centres) < k:
        d = np.min([((uniq - c) ** 2).sum(axis=1) for c in centres], axis=0)
        centres.append(uniq[np.argmax(d)])
    centres = np.asarray(centres, dtype=np.float32)
    for _ in range(iterations):
        labels = np.argmin(((pts[:, None, :] - centres[None, :, :]) ** 2).sum(axis=2), axis=1)
        for i in range(k):
            members = pts[labels == i]
            if len(members):
                centres[i] = members.mean(axis=0)
    return centres


def bake(im: Image.Image):
    src = np.asarray(im, dtype=np.float32)
    palettes, rows = [], []
    for y0 in range(0, HEIGHT, BAND_ROWS):
        band = src[y0 : y0 + BAND_ROWS].reshape(-1, 3)
        centres = band_palette(band)
        # darkest colour first, so index 0 (the band background) is the darkest
        centres = centres[np.argsort(centres.sum(axis=1))]
        labels = np.argmin(((band[:, None, :] - centres[None, :, :]) ** 2).sum(axis=2), axis=1)
        palettes.append([rgb565(tuple(int(round(v)) for v in c)) for c in centres])
        labels = labels.reshape(BAND_ROWS, WIDTH)
        for y in range(BAND_ROWS):
            rows.append([int(v) for v in labels[y]])
    data = []
    for row in rows:
        for x in range(0, WIDTH, 4):
            b = 0
            for k in range(4):
                b |= row[x + k] << (k * 2)
            data.append(b)
    preview = Image.new("RGB", (WIDTH, HEIGHT))
    for y, row in enumerate(rows):
        pal = palettes[y // BAND_ROWS]
        for x, i in enumerate(row):
            v = pal[i]
            preview.putpixel((x, y), (((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31))
    return palettes, data, preview


def main():
    lines = [
        "#pragma once",
        "// GENERATED by tools/hs02-ui-images/gen_preset_images.py -- do not edit by hand.",
        "// Pictures for the ready screen (presets 1..3) and the standby screen: 160x64, 2bpp (4 px per byte, LSB first),",
        f"// one 4-colour RGB565 palette per {BAND_ROWS}-row band.",
        "#include <stdint.h>",
        "",
        "namespace Hs02PresetImages {",
        f"constexpr uint8_t kPicW = {WIDTH}, kPicH = {HEIGHT}, kPicBandRows = {BAND_ROWS}, kPicBands = {HEIGHT // BAND_ROWS};",
        "struct Picture {",
        "  uint16_t       palettes[kPicBands][4];",
        "  const uint8_t *data;",
        "};",
        "",
    ]
    total = 0
    baked = []
    for n, name in enumerate(NAMES, 1):
        src = SRC_DIR / f"{name}.png"
        palettes, data, preview = bake(load(src))
        baked.append(palettes)
        preview.save(SRC_DIR / f"preview_{name}.png")
        total += len(data) + len(palettes) * 8
        lines.append(f"// {name}.png")
        lines.append(f"constexpr uint8_t kData{n}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(f"0x{b:02X}" for b in data[i : i + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("constexpr uint8_t kStandby = 3; // kPictures[0..2] = presets 1..3")
    lines.append(f"constexpr Picture kPictures[{len(NAMES)}] = {{")
    for n, palettes in enumerate(baked, 1):
        pal = ", ".join("{" + ", ".join(f"0x{c:04X}" for c in p) + "}" for p in palettes)
        lines.append(f"    {{{{{pal}}}, kData{n}}},")
    lines.append("};")
    lines.append("} // namespace Hs02PresetImages")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} (~{total} bytes of flash); previews in {SRC_DIR.relative_to(ROOT)}/preview_*.png")


if __name__ == "__main__":
    sys.exit(main())
